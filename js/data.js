// 搜索梦境关键词的函数
function searchDreamKeywords(dreamText) {
    const results = [];
    const lowerDreamText = dreamText.toLowerCase();
    
    // 遍历所有分类
    for (const [category, items] of Object.entries(dreamDictionary)) {
        // 遍历每个词条
        for (const item of items) {
            const keyword = item.keyword.toLowerCase();
            // 如果梦境文本包含关键词
            if (lowerDreamText.includes(keyword)) {
                results.push({
                    category,
                    ...item
                });
            }
        }
    }
    
    return results;
}

// 获取所有梦境分类
function getAllCategories() {
    return Object.keys(dreamDictionary);
}

// 获取指定分类的梦境词条
function getDreamsByCategory(category) {
    if (category === 'all') {
        // 返回所有分类的词条
        const allDreams = [];
        for (const items of Object.values(dreamDictionary)) {
            allDreams.push(...items);
        }
        return allDreams;
    }
    return dreamDictionary[category] || [];
}